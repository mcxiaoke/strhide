#!/usr/bin/env python3
"""Regenerate the third-party license inventories under `docs/licenses/`.

Three lists are produced, all from data that is already on disk:

* ``rust-core.md``     — every crate reachable from the `strhide` crate
                         (`cargo metadata`, all features, build deps included,
                         dev-deps excluded) because that is what a published
                         binary contains.
* ``gui-backend.md``   — every crate reachable from `gui/src-tauri`
                         (the Tauri runtime and the core engine).
* ``gui-frontend.md``  — every JavaScript package reachable from the GUI's
                         runtime dependencies in `gui/package.json`.

Usage (from the repository root):

    python scripts/gen_third_party_licenses.py          # regenerate the lists
    python scripts/gen_third_party_licenses.py --check   # fail if stale (CI)

`--check` compares the freshly rendered content against the committed files and
exits non-zero when they differ, so a dependency bump cannot silently leave the
attribution table out of date.
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "licenses"

HEADER = (
    "<!-- Generated by scripts/gen_third_party_licenses.py — do not edit by hand. -->\n"
    "> 本文件由 `scripts/gen_third_party_licenses.py` 生成，请勿手工编辑。\n"
    "> 重新生成：`python scripts/gen_third_party_licenses.py`（`--check` 用于 CI 校验）。\n"
    "> 许可证字段来自各包自身的元数据，未经人工逐项复核；分发二进制前请按需核对。\n\n"
)


def cargo_metadata(manifest_dir: Path) -> dict:
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--all-features"],
        cwd=manifest_dir,
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    ).stdout
    return json.loads(out)


def reachable_crates(meta: dict) -> list[tuple[str, str, str, str]]:
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    root = meta["resolve"]["root"]

    seen: set[str] = set()
    stack = [root]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            kinds = dep.get("dep_kinds") or [{}]
            # kind == None is a normal dependency, "build" is a build script dep.
            if any(k.get("kind") in (None, "build") for k in kinds):
                stack.append(dep["pkg"])

    rows = []
    for pid in seen:
        if pid == root:
            continue
        pkg = packages[pid]
        license_id = pkg.get("license") or "; ".join(pkg.get("license_file") or []) or "UNKNOWN"
        rows.append(
            (
                pkg["name"],
                pkg["version"],
                license_id,
                pkg.get("repository") or pkg.get("homepage") or "",
            )
        )
    rows.sort(key=lambda r: (r[0].lower(), r[1]))
    return rows


def render_crates(title: str, source: str, rows: list[tuple[str, str, str, str]]) -> str:
    counts: dict[str, int] = defaultdict(int)
    for _, _, lic, _ in rows:
        counts[lic] += 1

    parts = [HEADER]
    parts.append(f"# {title}\n\n")
    parts.append(f"来源：`{source}` · 共 **{len(rows)}** 个 crate（含 build 依赖，不含 dev-dependencies）。\n\n")
    parts.append("### 许可证分布\n\n")
    parts.append("| 许可证表达式 | 数量 |\n| :--- | ---: |\n")
    for lic, count in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        parts.append(f"| `{lic}` | {count} |\n")
    parts.append("\n### 清单\n\n")
    parts.append("| Crate | Version | License | 上游仓库 |\n| :--- | :--- | :--- | :--- |\n")
    for name, version, lic, repo in rows:
        parts.append(f"| `{name}` | {version} | {lic} | {repo or '—'} |\n")
    return "".join(parts)


def node_package_json(gui: Path, name: str, cache: dict[str, dict | None]) -> dict | None:
    """Resolve a package's package.json, including pnpm's nested store layout."""
    if name in cache:
        return cache[name]

    candidates = [gui / "node_modules" / name / "package.json"]
    store = gui / "node_modules" / ".pnpm"
    if store.is_dir():
        prefix = name.replace("/", "+") + "@"
        for entry in store.iterdir():
            if entry.name.startswith(prefix):
                candidates.append(entry / "node_modules" / name / "package.json")

    for path in candidates:
        if path.is_file():
            data = json.loads(path.read_text(encoding="utf-8"))
            cache[name] = data
            return data
    cache[name] = None
    return None


def gui_frontend_rows(gui: Path) -> list[tuple[str, str, str]]:
    root_pkg = json.loads((gui / "package.json").read_text(encoding="utf-8"))
    cache: dict[str, dict | None] = {}
    seen: dict[str, dict | None] = {}
    stack = list((root_pkg.get("dependencies") or {}).keys())

    while stack:
        name = stack.pop()
        if name in seen:
            continue
        data = node_package_json(gui, name, cache)
        seen[name] = data
        if data:
            for dep in data.get("dependencies") or {}:
                if dep not in seen:
                    stack.append(dep)

    rows = []
    for name, data in sorted(seen.items()):
        if data is None:
            rows.append((name, "?", "UNKNOWN (not installed)"))
        else:
            rows.append((name, data.get("version", "?"), data.get("license") or "UNKNOWN"))
    return rows


def render_frontend(rows: list[tuple[str, str, str]]) -> str:
    counts: dict[str, int] = defaultdict(int)
    for _, _, lic in rows:
        counts[lic] += 1

    parts = [HEADER]
    parts.append("# GUI 前端运行时依赖（JavaScript）\n\n")
    parts.append(
        f"来源：`gui/package.json` 的 `dependencies` 及其传递依赖 · 共 **{len(rows)}** 个包。\n"
        "开发依赖（Vite、TypeScript、Tailwind、Playwright 等）不随产物分发，故不列入。\n\n"
    )
    parts.append("### 许可证分布\n\n| 许可证 | 数量 |\n| :--- | ---: |\n")
    for lic, count in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0])):
        parts.append(f"| `{lic}` | {count} |\n")
    parts.append("\n### 清单\n\n| Package | Version | License |\n| :--- | :--- | :--- |\n")
    for name, version, lic in rows:
        parts.append(f"| `{name}` | {version} | {lic} |\n")
    return "".join(parts)


def main(argv: list[str]) -> int:
    check = "--check" in argv

    if shutil.which("cargo") is None:
        print("error: cargo not found in PATH", file=sys.stderr)
        return 2

    outputs: dict[Path, str] = {}

    core_meta = cargo_metadata(ROOT / "rust")
    outputs[OUT_DIR / "rust-core.md"] = render_crates(
        "strhide 核心 crate 依赖（Rust）",
        "rust/Cargo.toml · cargo metadata --all-features",
        reachable_crates(core_meta),
    )

    gui_meta = cargo_metadata(ROOT / "gui" / "src-tauri")
    outputs[OUT_DIR / "gui-backend.md"] = render_crates(
        "桌面端后端依赖（Tauri，Rust）",
        "gui/src-tauri/Cargo.toml · cargo metadata --all-features",
        reachable_crates(gui_meta),
    )

    outputs[OUT_DIR / "gui-frontend.md"] = render_frontend(gui_frontend_rows(ROOT / "gui"))

    if check:
        stale = []
        for path, content in outputs.items():
            current = path.read_text(encoding="utf-8") if path.is_file() else ""
            if current != content:
                stale.append(path.relative_to(ROOT).as_posix())
        if stale:
            print("stale license inventories:", file=sys.stderr)
            for item in stale:
                print(f"  {item}", file=sys.stderr)
            print("run: python scripts/gen_third_party_licenses.py", file=sys.stderr)
            return 1
        print("license inventories up to date")
        return 0

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for path, content in outputs.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print(f"wrote {path.relative_to(ROOT).as_posix()} ({content.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
